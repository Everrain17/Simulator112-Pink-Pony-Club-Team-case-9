const allChecklists = {};
Object.entries(CHECKLIST_TYPE_MAP).forEach(([type, template]) => {
    if (CHECKLIST_TEMPLATES[template]) {
        allChecklists[type] = CHECKLIST_TEMPLATES[template];
    }
});
Object.entries(CHECKLIST_TEMPLATES).forEach(([template, fields]) => {
    if (!allChecklists[template]) {
        allChecklists[template] = fields;
    }
});

function getChecklistType(typeName) {
    if (!typeName) return "default";
    const normalized = String(typeName).replace(/^\d+\.\s*/, "").trim();

    if (typeof runtimeClassifierCatalog !== "undefined") {
        const definition = (runtimeClassifierCatalog.incidentTypes || []).find(item =>
            String(item.code || "") === normalized ||
            String(item.name || "") === normalized
        );
        if (definition?.name && CHECKLIST_TYPE_MAP[definition.name]) {
            return CHECKLIST_TYPE_MAP[definition.name];
        }
        if (definition?.code && CHECKLIST_TYPE_MAP[definition.code]) {
            return CHECKLIST_TYPE_MAP[definition.code];
        }
    }

    if (CHECKLIST_TYPE_MAP[normalized]) {
        return CHECKLIST_TYPE_MAP[normalized];
    }

    return "default";
}

